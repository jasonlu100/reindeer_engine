_CURRENT = "en"


def set_language(code: str) -> None:
    global _CURRENT
    if code in _TRANSLATIONS:
        _CURRENT = code


def get_language() -> str:
    return _CURRENT


def available_languages():
    """Return a list of ``(code, display_name)`` tuples."""
    return [("en", "English"), ("zh_CN", "简体中文")]


def tr(key: str, **kwargs) -> str:
    """Translate ``key`` for the active language, formatting with ``kwargs``."""
    table = _TRANSLATIONS.get(_CURRENT, {})
    s = table.get(key)
    if s is None:
        s = _TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return s.format(**kwargs)
        except Exception:
            return s
    return s
